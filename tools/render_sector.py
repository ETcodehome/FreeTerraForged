def to_int32(val):
    val = val & 0xFFFFFFFF
    if val >= 0x80000000:
        val -= 0x100000000
    return val

def cell_vec(seed, x, y):
    h = seed
    h = to_int32(h ^ to_int32(1619 * x))
    h = to_int32(h ^ to_int32(31337 * y))
    prod = to_int32(h * h)
    prod = to_int32(prod * h)
    prod = to_int32(prod * 60493)
    h = to_int32(prod ^ (prod >> 13))
    return CELL_2D[h & 0xFF]

def save_bmp(filename, array):
    h, w = array.shape
    row_padded = (w + 3) & ~3
    header_size = 54
    palette_size = 256 * 4
    image_size = row_padded * h
    file_size = header_size + palette_size + image_size
    with open(filename, 'wb') as f:
        f.write(b'BM')
        f.write(struct.pack('<IHHI', file_size, 0, 0, header_size + palette_size))
        f.write(struct.pack('<IIIHHIIIIII', 40, w, h, 1, 8, 0, image_size, 2835, 2835, 256, 256))
        for i in range(256):
            f.write(struct.pack('BBBB', i, i, i, 0))
        for y in range(h - 1, -1, -1):
            row = bytes(array[y, :])
            f.write(row)
            if row_padded > w:
                f.write(b'\x00' * (row_padded - w))

def get_sector_clipped_uplift(x, y, seed=12345, jitter=0.8, saddle_height=0.75, active_bridged_only=True):
    xi = int(np.floor(x))
    yi = int(np.floor(y))
    cellPointX = x
    cellPointY = y
    cellX = xi
    cellY = yi
    nearestSq = float('inf')
    for cy in range(yi - 1, yi + 2):
        for cx in range(xi - 1, xi + 2):
            vx, vy = cell_vec(seed, cx, cy)
            px = cx + vx * jitter
            py = cy + vy * jitter
            d2 = (x - px)**2 + (y - py)**2
            if d2 < nearestSq:
                nearestSq = d2
                cellPointX = px
                cellPointY = py
                cellX = cx
                cellY = cy

    # 8 neighbors
    neighborX = []
    neighborY = []
    cx_list = []
    cy_list = []
    for cy2 in range(cellY - 1, cellY + 2):
        for cx2 in range(cellX - 1, cellX + 2):
            if cx2 != cellX or cy2 != cellY:
                vx2, vy2 = cell_vec(seed, cx2, cy2)
                cx_list.append(cx2)
                cy_list.append(cy2)
                neighborX.append(cx2 + vx2 * jitter)
                neighborY.append(cy2 + vy2 * jitter)

    s0Sq = cellPointX**2 + cellPointY**2
    minIndex = -1
    minGradient = float('inf')
    nx, ny, mx, my = [0.0]*8, [0.0]*8, [0.0]*8, [0.0]*8
    planeValue = [1.0]*8
    
    for i in range(8):
        px2 = neighborX[i]
        py2 = neighborY[i]
        dx = px2 - cellPointX
        dy = py2 - cellPointY
        l2 = dx*dx + dy*dy
        if l2 > 1e-5:
            l = np.sqrt(l2)
            nx[i] = dx / l
            ny[i] = dy / l
            mx[i] = (cellPointX + px2) * 0.5
            my[i] = (cellPointY + py2) * 0.5
            siSq = px2*px2 + py2*py2
            baseHalfDiff = 0.5 * (siSq - s0Sq)
            h_x = baseHalfDiff - (x * dx + y * dy)
            h_c = baseHalfDiff - (cellPointX * dx + cellPointY * dy)
            if h_c > 1e-5:
                pv = h_x / h_c
                planeValue[i] = pv
                if pv < minGradient:
                    minGradient = pv
                    minIndex = i

    if minIndex < 0 or minGradient >= 1.0:
        return 1.0
        
    clampedMin = max(0.0, minGradient)
    r = 1.0 - clampedMin
    if r <= 1e-5:
        return 1.0

    # In partial bridge mode, only bridge if edge satisfies hash
    if active_bridged_only:
        ax, ay, bx, by = cellX, cellY, cx_list[minIndex], cy_list[minIndex]
        if ax > bx or (ax == bx and ay > by):
            ax, ay, bx, by = bx, by, ax, ay
        h = 54321 ^ (bx * 73856093) ^ (by * 19349663) ^ (ax * 1619) ^ (ay * 31337)
        h = (h & 0xFFFF) / 65535.0
        # For this test, let's say only 1 specific neighbor of (0, 0) is bridged (e.g. upper right)
        # to test single bridge behavior matching user image
        if h >= 0.5:
            return clampedMin

    # True bisector clipping
    tx = -ny[minIndex]
    ty = nx[minIndex]
    lo = -1.0e9
    hi = 1.0e9
    ok = True
    for j in range(8):
        if not ok: break
        if j == minIndex: continue
        a = tx * nx[j] + ty * ny[j]
        b = (mx[j] - mx[minIndex]) * nx[j] + (my[j] - my[minIndex]) * ny[j]
        if abs(a) < 1e-6:
            if b < 0: ok = False
            continue
        t = b / a
        if a > 0:
            if t < hi: hi = t
        elif t > lo:
            lo = t

    if not ok or lo >= hi or lo <= -1.0e8 or hi >= 1.0e8:
        return clampedMin

    # Normalized ray projection onto bisector
    d_tan = (x - mx[minIndex]) * tx + (y - my[minIndex]) * ty
    t_edge = d_tan / r
    
    # Exact center of Voronoi edge [lo, hi]
    t_center = 0.5 * (lo + hi)
    halfLen = 0.5 * (hi - lo)
    if halfLen <= 1e-6:
        return clampedMin
        
    fraction = abs(t_edge - t_center) / halfLen
    if fraction >= 1.0:
        return clampedMin
        
    f = fraction
    lateralFade = 1.0 - (3.0 * f * f - 2.0 * f * f * f)
    edgeHeight = saddle_height * lateralFade
    bridged = clampedMin + r * edgeHeight
    return np.clip(bridged, 0.0, 1.0)

